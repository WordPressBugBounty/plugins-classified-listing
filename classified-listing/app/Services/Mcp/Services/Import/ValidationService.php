<?php

namespace Rtcl\Services\Mcp\Services\Import;

use Rtcl\Services\Mcp\ErrorCodes;

defined( 'ABSPATH' ) || exit;

/**
 * Validates listing import data without modifying the database.
 *
 * Used for dry-run validation before bulk imports.
 */
class ValidationService {

	/**
	 * @var TaxonomyResolver
	 */
	private $taxonomy_resolver;

	public function __construct( ?TaxonomyResolver $taxonomy_resolver = null ) {
		$this->taxonomy_resolver = $taxonomy_resolver ?: new TaxonomyResolver();
	}

	/**
	 * Validate a single listing item.
	 *
	 * @param array $item Item data to validate.
	 *
	 * @return array {
	 *     @type bool   $valid    Whether the item is valid.
	 *     @type array  $errors   Array of error details.
	 *     @type array  $warnings Array of warning details.
	 * }
	 */
	public function validateItem( array $item ): array {
		$errors = [];
		$warnings = [];

		// external_id: generated by the importer when missing (McpImporter::ensureExternalId()).
		if ( empty( $item['external_id'] ) ) {
			$warnings[] = [
				'code'    => ErrorCodes::MISSING_EXTERNAL_ID,
				'field'   => 'external_id',
				'message' => __( 'No external_id: one will be generated from title, category and location. Provide your own ID to update these listings reliably later.', 'classified-listing' ),
			];
		}

		// Required: title
		if ( empty( $item['title'] ) ) {
			$errors[] = [
				'code'    => ErrorCodes::VALIDATION_REQUIRED_FIELD,
				'field'   => 'title',
				'message' => __( 'Title is required.', 'classified-listing' ),
			];
		}

		// Validate slug
		if ( ! empty( $item['slug'] ) ) {
			$slug = sanitize_title( $item['slug'] );
			if ( empty( $slug ) ) {
				$warnings[] = [
					'code'    => ErrorCodes::VALIDATION_INVALID_TYPE,
					'field'   => 'slug',
					'message' => __( 'Invalid slug format. Will be auto-generated from title.', 'classified-listing' ),
				];
			}
		}

		// Validate form_id
		if ( ! empty( $item['form_id'] ) ) {
			$form_id = absint( $item['form_id'] );
			if ( $form_id > 0 ) {
				$form = get_post( $form_id );
				if ( ! $form || 'rtcl_fb_form' !== $form->post_type ) {
					$warnings[] = [
						'code'    => 'invalid_form_id',
						'field'   => 'form_id',
						'message' => sprintf( __( 'Form ID %d not found.', 'classified-listing' ), $form_id ),
					];
				}
			}
		}

		// Validate form_slug
		if ( ! empty( $item['form_slug'] ) ) {
			$form_posts = get_posts( [
				'post_type'      => 'rtcl_fb_form',
				'name'           => sanitize_key( $item['form_slug'] ),
				'posts_per_page' => 1,
				'post_status'    => 'publish',
				'fields'         => 'ids',
			] );
			if ( empty( $form_posts ) ) {
				$warnings[] = [
					'code'    => 'invalid_form_slug',
					'field'   => 'form_slug',
					'message' => sprintf( __( 'Form with slug "%s" not found.', 'classified-listing' ), $item['form_slug'] ),
				];
			}
		}

		// Validate price
		if ( isset( $item['price'] ) && ! is_numeric( $item['price'] ) ) {
			$errors[] = [
				'code'    => ErrorCodes::VALIDATION_INVALID_TYPE,
				'field'   => 'price',
				'message' => __( 'Price must be a number.', 'classified-listing' ),
			];
		}

		if ( isset( $item['price'] ) && is_numeric( $item['price'] ) && $item['price'] < 0 ) {
			$errors[] = [
				'code'    => ErrorCodes::VALIDATION_INVALID_PRICE,
				'field'   => 'price',
				'message' => __( 'Price cannot be negative.', 'classified-listing' ),
			];
		}

		// Validate max_price
		if ( isset( $item['max_price'] ) && ! is_numeric( $item['max_price'] ) ) {
			$errors[] = [
				'code'    => ErrorCodes::VALIDATION_INVALID_TYPE,
				'field'   => 'max_price',
				'message' => __( 'Max price must be a number.', 'classified-listing' ),
			];
		}

		if ( isset( $item['max_price'] ) && isset( $item['price'] ) && is_numeric( $item['max_price'] ) && is_numeric( $item['price'] ) ) {
			if ( $item['max_price'] < $item['price'] ) {
				$warnings[] = [
					'code'    => ErrorCodes::VALIDATION_INVALID_PRICE,
					'field'   => 'max_price',
					'message' => __( 'Max price should be greater than or equal to price.', 'classified-listing' ),
				];
			}
		}

		// Validate pricing_type
		if ( ! empty( $item['pricing_type'] ) ) {
			$allowed_types = [ 'price', 'range', 'disabled' ];
			if ( ! in_array( $item['pricing_type'], $allowed_types, true ) ) {
				$errors[] = [
					'code'    => ErrorCodes::VALIDATION_INVALID_ENUM,
					'field'   => 'pricing_type',
					'message' => sprintf(
						/* translators: %s: Allowed values */
						__( 'Invalid pricing type. Allowed: %s', 'classified-listing' ),
						implode( ', ', $allowed_types )
					),
				];
			}
		}

		// Validate featured
		if ( isset( $item['featured'] ) && ! is_bool( $item['featured'] ) && ! in_array( $item['featured'], [ 0, 1, '0', '1', true, false ], true ) ) {
			$warnings[] = [
				'code'    => ErrorCodes::VALIDATION_INVALID_TYPE,
				'field'   => 'featured',
				'message' => __( 'Featured must be a boolean value.', 'classified-listing' ),
			];
		}

		// Validate listing_type
		if ( ! empty( $item['listing_type'] ) ) {
			$allowed_types = [ 'sell', 'buy', 'exchange', 'job', 'to_let' ];
			if ( ! in_array( $item['listing_type'], $allowed_types, true ) ) {
				$errors[] = [
					'code'    => ErrorCodes::VALIDATION_INVALID_ENUM,
					'field'   => 'listing_type',
					'message' => sprintf(
						/* translators: %s: Allowed values */
						__( 'Invalid listing type. Allowed: %s', 'classified-listing' ),
						implode( ', ', $allowed_types )
					),
				];
			}
		}

		// Validate price_type
		if ( ! empty( $item['price_type'] ) ) {
			$allowed_types = [ 'regular', 'on_call', 'negotiable', 'fixed' ];
			if ( ! in_array( $item['price_type'], $allowed_types, true ) ) {
				$errors[] = [
					'code'    => ErrorCodes::VALIDATION_INVALID_ENUM,
					'field'   => 'price_type',
					'message' => sprintf(
						/* translators: %s: Allowed values */
						__( 'Invalid price type. Allowed: %s', 'classified-listing' ),
						implode( ', ', $allowed_types )
					),
				];
			}
		}

		// Validate status
		if ( ! empty( $item['status'] ) ) {
			$allowed_statuses = [ 'publish', 'pending', 'draft' ];
			if ( ! in_array( $item['status'], $allowed_statuses, true ) ) {
				$errors[] = [
					'code'    => ErrorCodes::VALIDATION_INVALID_ENUM,
					'field'   => 'status',
					'message' => sprintf(
						/* translators: %s: Allowed values */
						__( 'Invalid status. Allowed: %s', 'classified-listing' ),
						implode( ', ', $allowed_statuses )
					),
				];
			}
		}

		// Validate category
		if ( ! empty( $item['category'] ) ) {
			$category_result = $this->taxonomy_resolver->resolveCategory( $item['category'] );
			if ( is_wp_error( $category_result ) ) {
				$errors[] = [
					'code'    => ErrorCodes::CATEGORY_NOT_FOUND,
					'field'   => 'category',
					'message' => $category_result->get_error_message(),
				];
			}
		}

		// Validate location
		if ( ! empty( $item['location'] ) ) {
			$location_result = $this->taxonomy_resolver->resolveLocation( $item['location'] );
			if ( is_wp_error( $location_result ) ) {
				// Location errors are warnings, not hard failures
				$warnings[] = [
					'code'    => ErrorCodes::LOCATION_NOT_FOUND,
					'field'   => 'location',
					'message' => $location_result->get_error_message(),
				];
			}
		}

		// Validate images
		if ( ! empty( $item['images'] ) ) {
			if ( ! is_array( $item['images'] ) ) {
				$errors[] = [
					'code'    => ErrorCodes::VALIDATION_INVALID_TYPE,
					'field'   => 'images',
					'message' => __( 'Images must be an array of URLs.', 'classified-listing' ),
				];
			} else {
				foreach ( $item['images'] as $index => $url ) {
					if ( ! filter_var( $url, FILTER_VALIDATE_URL ) ) {
						$warnings[] = [
							'code'    => ErrorCodes::VALIDATION_INVALID_URL,
							'field'   => "images[$index]",
							'message' => sprintf(
								/* translators: %s: Invalid URL */
								__( 'Invalid image URL: %s', 'classified-listing' ),
								$url
							),
						];
					}
				}
			}
		}

		// Validate contact email
		if ( ! empty( $item['contact']['email'] ) && ! is_email( $item['contact']['email'] ) ) {
			$warnings[] = [
				'code'    => ErrorCodes::VALIDATION_INVALID_TYPE,
				'field'   => 'contact.email',
				'message' => __( 'Invalid email address format.', 'classified-listing' ),
			];
		}

		// Validate contact website
		if ( ! empty( $item['contact']['website'] ) && ! filter_var( $item['contact']['website'], FILTER_VALIDATE_URL ) ) {
			$warnings[] = [
				'code'    => ErrorCodes::VALIDATION_INVALID_URL,
				'field'   => 'contact.website',
				'message' => __( 'Invalid website URL.', 'classified-listing' ),
			];
		}

		// Validate video_urls
		if ( ! empty( $item['video_urls'] ) ) {
			if ( ! is_array( $item['video_urls'] ) ) {
				$errors[] = [
					'code'    => ErrorCodes::VALIDATION_INVALID_TYPE,
					'field'   => 'video_urls',
					'message' => __( 'Video URLs must be an array.', 'classified-listing' ),
				];
			} else {
				$allowed_hosts = [ 'youtube.com', 'youtu.be', 'vimeo.com', 'www.youtube.com', 'www.vimeo.com' ];
				foreach ( $item['video_urls'] as $index => $url ) {
					if ( ! filter_var( $url, FILTER_VALIDATE_URL ) ) {
						$warnings[] = [
							'code'    => ErrorCodes::VALIDATION_INVALID_URL,
							'field'   => "video_urls[$index]",
							'message' => sprintf( __( 'Invalid video URL: %s', 'classified-listing' ), $url ),
						];
					} else {
						$host = parse_url( $url, PHP_URL_HOST );
						if ( ! in_array( $host, $allowed_hosts, true ) ) {
							$warnings[] = [
								'code'    => ErrorCodes::VALIDATION_INVALID_URL,
								'field'   => "video_urls[$index]",
								'message' => sprintf( __( 'Video URL must be from YouTube or Vimeo: %s', 'classified-listing' ), $url ),
							];
						}
					}
				}
			}
		}

		// Validate geo_location
		if ( ! empty( $item['geo_location'] ) ) {
			if ( ! is_array( $item['geo_location'] ) ) {
				$errors[] = [
					'code'    => ErrorCodes::VALIDATION_INVALID_TYPE,
					'field'   => 'geo_location',
					'message' => __( 'Geo location must be an object with latitude and longitude.', 'classified-listing' ),
				];
			} else {
				$lat = $item['geo_location']['latitude'] ?? null;
				$lng = $item['geo_location']['longitude'] ?? null;

				if ( null !== $lat && ( ! is_numeric( $lat ) || $lat < -90 || $lat > 90 ) ) {
					$errors[] = [
						'code'    => ErrorCodes::VALIDATION_INVALID_TYPE,
						'field'   => 'geo_location.latitude',
						'message' => __( 'Latitude must be a number between -90 and 90.', 'classified-listing' ),
					];
				}

				if ( null !== $lng && ( ! is_numeric( $lng ) || $lng < -180 || $lng > 180 ) ) {
					$errors[] = [
						'code'    => ErrorCodes::VALIDATION_INVALID_TYPE,
						'field'   => 'geo_location.longitude',
						'message' => __( 'Longitude must be a number between -180 and 180.', 'classified-listing' ),
					];
				}
			}
		}

		// Validate business_hours
		if ( ! empty( $item['business_hours'] ) ) {
			if ( ! is_array( $item['business_hours'] ) ) {
				$errors[] = [
					'code'    => ErrorCodes::VALIDATION_INVALID_TYPE,
					'field'   => 'business_hours',
					'message' => __( 'Business hours must be an object with day names as keys.', 'classified-listing' ),
				];
			} else {
				$valid_days = [ 'monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'saturday', 'sunday' ];
				foreach ( array_keys( $item['business_hours'] ) as $day ) {
					if ( ! in_array( $day, $valid_days, true ) ) {
						$warnings[] = [
							'code'    => ErrorCodes::VALIDATION_INVALID_TYPE,
							'field'   => "business_hours.$day",
							'message' => sprintf( __( 'Invalid day name: %s', 'classified-listing' ), $day ),
						];
					}
				}
			}
		}

		// Validate social_profiles
		if ( ! empty( $item['social_profiles'] ) ) {
			if ( ! is_array( $item['social_profiles'] ) ) {
				$errors[] = [
					'code'    => ErrorCodes::VALIDATION_INVALID_TYPE,
					'field'   => 'social_profiles',
					'message' => __( 'Social profiles must be an object with network names as keys.', 'classified-listing' ),
				];
			} else {
				foreach ( $item['social_profiles'] as $network => $url ) {
					if ( ! filter_var( $url, FILTER_VALIDATE_URL ) ) {
						$warnings[] = [
							'code'    => ErrorCodes::VALIDATION_INVALID_URL,
							'field'   => "social_profiles.$network",
							'message' => sprintf( __( 'Invalid URL for %s.', 'classified-listing' ), $network ),
						];
					}
				}
			}
		}

		// Validate custom_fields structure
		if ( ! empty( $item['custom_fields'] ) ) {
			if ( ! is_array( $item['custom_fields'] ) ) {
				$errors[] = [
					'code'    => ErrorCodes::VALIDATION_INVALID_TYPE,
					'field'   => 'custom_fields',
					'message' => __( 'Custom fields must be an object.', 'classified-listing' ),
				];
			} else {
				// Validate date range fields
				foreach ( $item['custom_fields'] as $key => $value ) {
					if ( is_array( $value ) && ( isset( $value['start'] ) || isset( $value['end'] ) ) ) {
						// Date range field - validate dates
						if ( ! empty( $value['start'] ) && ! strtotime( $value['start'] ) ) {
							$warnings[] = [
								'code'    => ErrorCodes::VALIDATION_INVALID_TYPE,
								'field'   => "custom_fields.$key.start",
								'message' => __( 'Invalid start date format.', 'classified-listing' ),
							];
						}
						if ( ! empty( $value['end'] ) && ! strtotime( $value['end'] ) ) {
							$warnings[] = [
								'code'    => ErrorCodes::VALIDATION_INVALID_TYPE,
								'field'   => "custom_fields.$key.end",
								'message' => __( 'Invalid end date format.', 'classified-listing' ),
							];
						}
						// Check end after start
						if ( ! empty( $value['start'] ) && ! empty( $value['end'] ) ) {
							if ( strtotime( $value['end'] ) < strtotime( $value['start'] ) ) {
								$warnings[] = [
									'code'    => ErrorCodes::VALIDATION_INVALID_TYPE,
									'field'   => "custom_fields.$key",
									'message' => __( 'End date must be after start date.', 'classified-listing' ),
								];
							}
						}
					}
				}
			}
		}

		return [
			'valid'    => empty( $errors ),
			'errors'   => $errors,
			'warnings' => $warnings,
		];
	}

	/**
	 * Validate a batch of items.
	 *
	 * @param string $source Source identifier.
	 * @param array  $items  Array of items to validate.
	 *
	 * @return array {
	 *     @type bool   $valid         Whether all items are valid.
	 *     @type int    $total_items   Total number of items.
	 *     @type int    $valid_items   Number of valid items.
	 *     @type int    $invalid_items Number of invalid items.
	 *     @type array  $results       Per-item validation results.
	 * }
	 */
	public function validateBatch( string $source, array $items ): array {
		$results = [];
		$valid_count = 0;
		$invalid_count = 0;
		$seen_external_ids = [];

		// Validate source
		if ( empty( $source ) ) {
			return [
				'valid'         => false,
				'total_items'   => count( $items ),
				'valid_items'   => 0,
				'invalid_items' => count( $items ),
				'results'       => [
					[
						'external_id' => null,
						'valid'       => false,
						'errors'      => [
							[
								'code'    => ErrorCodes::MISSING_SOURCE,
								'field'   => 'source',
								'message' => __( 'Source identifier is required.', 'classified-listing' ),
							],
						],
						'warnings'    => [],
					],
				],
			];
		}

		foreach ( $items as $index => $item ) {
			$external_id = $item['external_id'] ?? null;

			// Check for duplicate external_ids within the batch
			$item_errors = [];
			if ( $external_id && isset( $seen_external_ids[ $external_id ] ) ) {
				$item_errors[] = [
					'code'    => ErrorCodes::DUPLICATE_EXTERNAL_ID,
					'field'   => 'external_id',
					'message' => sprintf(
						/* translators: %s: External ID */
						__( 'Duplicate external_id "%s" in batch.', 'classified-listing' ),
						$external_id
					),
				];
			}

			if ( $external_id ) {
				$seen_external_ids[ $external_id ] = true;
			}

			$validation = $this->validateItem( $item );

			// Merge duplicate check errors
			$validation['errors'] = array_merge( $item_errors, $validation['errors'] );
			$validation['valid'] = empty( $validation['errors'] );

			if ( $validation['valid'] ) {
				$valid_count++;
			} else {
				$invalid_count++;
			}

			// Only include results for invalid items or items with warnings
			if ( ! $validation['valid'] || ! empty( $validation['warnings'] ) ) {
				$results[] = [
					'external_id' => $external_id,
					'index'       => $index,
					'valid'       => $validation['valid'],
					'errors'      => $validation['errors'],
					'warnings'    => $validation['warnings'],
				];
			}
		}

		return [
			'valid'         => $invalid_count === 0,
			'total_items'   => count( $items ),
			'valid_items'   => $valid_count,
			'invalid_items' => $invalid_count,
			'results'       => $results,
		];
	}
}
